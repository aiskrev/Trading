"""Supply chain (threat T14): dependencies are exactly pinned with hashes, consistent, and installed with hash checking."""
import importlib.util
import re
from pathlib import Path

import pytest
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("make_sbom", ROOT / "scripts" / "make_sbom.py")
sbom = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sbom)

LOCKS = {name: ROOT / "requirements" / f"{name}.lock" for name in ("runtime", "model", "dev")}
PYPROJECT = (ROOT / "pyproject.toml").read_text(encoding="utf-8")


def pins(name):
    return {p["name"]: p for p in sbom.parse_lock(LOCKS[name].read_text(encoding="utf-8"))}


def declared(section):
    """Requirement strings from pyproject.toml: `dependencies` or an optional-dependencies group."""
    if section == "dependencies":
        block = re.search(r"^dependencies = \[(.*?)^\]", PYPROJECT, re.S | re.M).group(1)
    else:
        block = re.search(rf"^{section} = \[(.*?)^\]", PYPROJECT, re.S | re.M).group(1)
    return [Requirement(m) for m in re.findall(r'^\s*"([^"]+)"', block, re.M)]


@pytest.mark.parametrize("name", sorted(LOCKS))
def test_every_entry_is_exactly_pinned_and_hashed(name):
    packages = sbom.parse_lock(LOCKS[name].read_text(encoding="utf-8"))   # raises on editable / URL / VCS / unpinned
    assert packages
    for p in packages:
        assert re.fullmatch(r"\d[\w.!+-]*", p["version"]), p
        assert p["hashes"], f"{p['name']} has no hash"
        assert len(set(p["hashes"])) == len(p["hashes"])


@pytest.mark.parametrize("name,section", [("runtime", "dependencies"), ("model", "model"), ("dev", "dev")])
def test_every_declared_dependency_is_locked_within_its_bounds(name, section):
    locked = pins(name)
    wanted = declared("dependencies") + (declared(section) if section != "dependencies" else [])
    assert wanted
    for req in wanted:
        key = sbom.normalize(req.name)
        assert key in locked, f"{req.name} is declared but not in {name}.lock"
        assert req.specifier.contains(locked[key]["version"], prereleases=True), \
            f"{req.name}{req.specifier} vs locked {locked[key]['version']}"


def test_the_locks_agree_on_every_shared_version():
    runtime, model, dev = pins("runtime"), pins("model"), pins("dev")
    for other in (model, dev):
        for name, p in runtime.items():
            assert other[name]["version"] == p["version"], name
            assert other[name]["hashes"] == p["hashes"], name
    for name in set(model) & set(dev):
        assert model[name]["version"] == dev[name]["version"], name


def test_the_model_sdk_is_only_in_the_model_lock():
    assert "anthropic" in pins("model") and "anthropic" not in pins("runtime") and "anthropic" not in pins("dev")


def test_the_pydantic_pin_matches_the_committed_schemas():
    """The JSON Schemas are generated by this pydantic minor version; a different one changes them (drift test)."""
    assert re.fullmatch(r"2\.13\.\d+", pins("runtime")["pydantic"]["version"])


def test_sbom_matches_the_model_lock():
    assert sbom.main(["--check"]) == 0
    assert (ROOT / "requirements" / "sbom.cdx.json").read_text(encoding="utf-8").count("pkg:pypi/") == len(pins("model"))


def test_ci_installs_with_hash_checking_and_the_declared_python():
    ci = (ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
    assert "--require-hashes -r requirements/dev.lock" in ci and "--no-deps -e ." in ci
    assert 'pip install -e ".[dev]"' not in ci                       # that would resolve fresh, unverified versions
    assert re.search(r'python-version:\s*"3\.12"', ci) and 'requires-python = ">=3.12"' in PYPROJECT
    assert "make_sbom.py --check" in ci


def test_no_tool_config_installs_unlocked_dependencies():
    for path in (ROOT / "README.md", ROOT / "requirements" / "README.md"):
        text = path.read_text(encoding="utf-8")
        assert 'pip install -e ".[dev]"' not in text, path.name
